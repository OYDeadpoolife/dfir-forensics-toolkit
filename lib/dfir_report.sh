#!/usr/bin/env bash
# shellcheck shell=bash disable=SC2016
# (SC2016: the Markdown backticks inside single quotes are intentional, nothing should expand.)
# Writes report/case_report.md. Sourced by bin/dfir-triage after the other libraries.
#
# The report states facts the toolkit recorded. It does not draw conclusions: those belong to
# the analyst (see templates/analyst-report-template.md). Text taken from the evidence is
# untrusted, so it is only ever placed inside fenced code blocks or escaped table cells.
#
# Globals read: CASE_ID, ANALYST, STARTED_AT, FINISHED_AT, COMMAND_LINE, EVIDENCE_PATH, EVIDENCE_NAME,
#               EVIDENCE_SIZE, SHA256_BEFORE, SHA256_AFTER, MD5_VALUE, INTEGRITY_RESULT, CASE_DIR,
#               STATUS_FILE, VERSIONS_FILE

# Escape a value for a Markdown table cell.
md_cell() {
    local text
    text=$(one_line "$1")
    printf '%s' "${text:--}" | LC_ALL=C sed -e 's/|/\&#124;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' -e "s/\`/'/g"
}

# Print lines from stdin inside a fenced block. The fence is longer than anything in the
# evidence can close, and non-printable bytes are replaced.
fenced_block() {
    printf '~~~~text\n'
    LC_ALL=C tr -c '\n\040-\176' '?' | LC_ALL=C sed -e 's/~~~~*/~~~/g'
    printf '~~~~\n'
}

# Same, for text the user supplied (such as the evidence path): only control characters are
# removed, so Hebrew or other non-ASCII path names stay readable.
fenced_block_user_text() {
    printf '~~~~text\n'
    LC_ALL=C tr -d '\000-\010\013\014\016-\037\177' | LC_ALL=C sed -e 's/~~~~*/~~~/g'
    printf '~~~~\n'
}

module_status_of() {
    local status
    status=$(awk -F '\t' -v m="$1" '$1 == m { value = $2 } END { print value }' "$STATUS_FILE")
    printf '%s' "${status:-NOT RUN}"
}

module_note_of() {
    awk -F '\t' -v m="$1" '$1 == m { value = $6 } END { print value }' "$STATUS_FILE"
}

# Print "Module not run" or the skip reason, and succeed only when the module produced output.
module_has_output() {
    local module=$1 status
    status=$(module_status_of "$module")
    case $status in
        OK | FAILED | TIMEOUT) return 0 ;;
        SKIPPED) printf '*%s was skipped: %s*\n\n' "$module" "$(md_cell "$(module_note_of "$module")")" ;;
        *) printf '*%s was not requested for this run.*\n\n' "$module" ;;
    esac
    return 1
}

write_case_report() {
    local report=$CASE_DIR/report/case_report.md
    local module status rc started finished note name tool version
    {
        printf '# Case report: %s\n\n' "$(md_cell "$CASE_ID")"
        printf 'Generated by dfir-triage %s at %s (UTC).\n\n' "$DFIR_VERSION" "$FINISHED_AT"
        printf '> This is an automatically generated technical summary of what the toolkit did and recorded.\n'
        printf '> It contains no conclusions. The analyst'"'"'s findings belong in the analyst report.\n\n'

        printf '## 1. Case information\n\n| Field | Value |\n|---|---|\n'
        printf '| Case ID | %s |\n| Analyst | %s |\n' "$(md_cell "$CASE_ID")" "$(md_cell "$ANALYST")"
        printf '| Started (UTC) | %s |\n| Finished (UTC) | %s |\n' "$STARTED_AT" "$FINISHED_AT"
        printf '| System | %s |\n' "$(md_cell "$(uname -sr)")"
        printf '| Command line | %s |\n\n' "$(md_cell "$COMMAND_LINE")"

        printf '## 2. Evidence\n\n| Field | Value |\n|---|---|\n'
        printf '| File name | %s |\n| Original path | %s |\n| Size | %s bytes |\n' \
            "$(md_cell "$EVIDENCE_NAME")" "$(md_cell "$EVIDENCE_PATH")" "$EVIDENCE_SIZE"
        printf '| File type | %s |\n' "$(md_cell "$(cat "$CASE_DIR/metadata/file_type.txt" 2>/dev/null)")"
        printf '| SHA-256 before analysis | `%s` |\n| SHA-256 after analysis | `%s` |\n' "$SHA256_BEFORE" "$SHA256_AFTER"
        if [[ -n $MD5_VALUE ]]; then
            printf '| MD5 (legacy, not for integrity) | `%s` |\n' "$MD5_VALUE"
        fi
        printf '| **Integrity check** | **%s** |\n\n' "$INTEGRITY_RESULT"
        printf 'File times as seen before the evidence was read (`metadata/file_attributes.txt`):\n\n'
        fenced_block_user_text <"$CASE_DIR/metadata/file_attributes.txt"
        printf '\n'

        printf '## 3. Execution summary\n\n'
        printf '| Module | Status | Exit code | Started (UTC) | Finished (UTC) | Note |\n|---|---|---|---|---|---|\n'
        while IFS=$'\t' read -r module status rc started finished note; do
            printf '| %s | %s | %s | %s | %s | %s |\n' "$module" "$status" "$rc" "$started" "$finished" "$(md_cell "$note")"
        done < <(tail -n +2 "$STATUS_FILE")
        printf '\nStatus values: **OK** finished; **FAILED** the module returned an error; **TIMEOUT** stopped by `--timeout`; '
        printf '**SKIPPED** the required program is not installed (nothing was installed automatically).\n\n'

        printf '## 4. Tool versions\n\n'
        if [[ -s $VERSIONS_FILE ]]; then
            printf '| Module | Program | Reported version |\n|---|---|---|\n'
            while IFS=$'\t' read -r name tool version; do
                printf '| %s | %s | %s |\n' "$name" "$(md_cell "$tool")" "$(md_cell "$version")"
            done <"$VERSIONS_FILE"
            printf '\n'
        else
            printf 'No external program was run.\n\n'
        fi

        printf '## 5. Output of the automated modules\n\n'
        printf '### 5.1 File type\n\n'
        if module_has_output metadata; then
            printf 'MIME type: `%s`\n\nFirst 64 bytes:\n\n' "$(md_cell "$(cat "$CASE_DIR/metadata/mime_type.txt" 2>/dev/null)")"
            fenced_block <"$CASE_DIR/metadata/first_64_bytes.hex.txt"
            printf '\n'
        fi

        printf '### 5.2 Indicators found in strings\n\n'
        if module_has_output strings; then
            printf 'IPv4 addresses, URLs and e-mail addresses (best effort; version numbers can look like addresses). Top 20:\n\n'
            head -n 21 "$CASE_DIR/strings/iocs.tsv" | fenced_block
            printf '\n'
        fi

        printf '### 5.3 binwalk (embedded file signatures)\n\n'
        if module_has_output binwalk; then
            head -n 40 "$CASE_DIR/binwalk/binwalk.stdout.txt" | fenced_block
            printf '\n'
        fi

        printf '### 5.4 foremost (carved files)\n\n'
        if module_has_output foremost; then
            if [[ -f $CASE_DIR/foremost/carved/audit.txt ]]; then
                head -n 40 "$CASE_DIR/foremost/carved/audit.txt" | fenced_block
            else
                head -n 20 "$CASE_DIR/foremost/foremost.stdout.txt" | fenced_block
            fi
            printf '\n'
        fi

        printf '### 5.5 bulk_extractor (features)\n\n'
        if module_has_output bulk_extractor; then
            head -n 20 "$CASE_DIR/bulk_extractor/bulk_extractor.stdout.txt" | fenced_block
            printf '\n'
        fi

        printf '### 5.6 Volatility 3\n\n'
        if module_has_output volatility; then
            printf 'One output file per plugin is stored in `volatility/`.\n\n'
        fi

        printf '## 6. Files in this case\n\n'
        (cd "$CASE_DIR" && LC_ALL=C find . -type f | LC_ALL=C sort) | fenced_block
        printf '\n'

        printf '## 7. Analyst section (complete by hand)\n\n'
        printf 'Copy `templates/analyst-report-template.md` from the toolkit and answer the investigation questions. Record here:\n\n'
        printf -- '- [ ] What the evidence is and where it came from (chain of custody)\n'
        printf -- '- [ ] Findings, each with the file or offset that supports it\n'
        printf -- '- [ ] Limitations and anything that could not be checked\n'
        printf -- '- [ ] Recommended next steps\n\n'

        printf '## 8. What this report cannot tell you\n\n'
        printf -- '- Whether the evidence is real, complete or acquired correctly: that depends on how it was collected.\n'
        printf -- '- Whether an indicator is malicious. Strings and carved files are leads, not verdicts.\n'
        printf -- '- Anything about modules that were skipped or failed.\n'
    } >"$report"
}
